import { z } from 'zod'

// What the web collects in Chromium without asking for permission, plus the
// monitors when the Window Management permission was granted. Every field is
// nullable: browsers expose different subsets.
const text = z.string().trim().max(200)
const count = z.number().int().min(0).max(10_000)
const measure = z.number().min(0).max(1_000_000)

// navigator.deviceMemory is coarse on purpose: a power of two, capped at 8 GB.
// Values outside that are snapped down to the nearest step, so a newer browser
// reporting more does not reject the whole report.
export const DEVICE_MEMORY_MAX_GB = 8
export const DEVICE_MEMORY_MIN_GB = 0.25

export function roundDeviceMemory(value: number): number {
  const capped = Math.min(Math.max(value, DEVICE_MEMORY_MIN_GB), DEVICE_MEMORY_MAX_GB)
  return 2 ** Math.floor(Math.log2(capped))
}

export const deviceMemorySchema = z.number().positive().max(1024).transform(roundDeviceMemory)

const codecSupportSchema = z.object({
  supported: z.boolean(),
  smooth: z.boolean(),
  powerEfficient: z.boolean(),
})

export const VIDEO_CODECS = ['h264', 'vp9', 'av1'] as const

export const displaySchema = z.object({
  label: text.nullable(),
  width: count,
  height: count,
  scaleFactor: z.number().positive().max(16),
  refreshRate: z.number().positive().max(1000).nullable(),
  isPrimary: z.boolean().nullable(),
  isInternal: z.boolean().nullable(),
})
export type Display = z.infer<typeof displaySchema>

export const collectedHardwareSchema = z.object({
  // User-Agent Client Hints.
  os: z.object({
    platform: text.nullable(),
    version: text.nullable(),
    architecture: text.nullable(),
    bitness: text.nullable(),
  }),
  browser: z.object({
    brand: text.nullable(),
    version: text.nullable(),
  }),
  logicalCores: count.nullable(),
  deviceMemoryGb: z.number().positive().max(DEVICE_MEMORY_MAX_GB).nullable(),
  gpu: z.object({
    vendor: text.nullable(),
    renderer: text.nullable(),
    hardwareAcceleration: z.boolean().nullable(),
    webgpu: z.boolean().nullable(),
  }),
  // Media Capabilities, encoding at 1080p60.
  videoEncoding: z.object({
    h264: codecSupportSchema.nullable(),
    vp9: codecSupportSchema.nullable(),
    av1: codecSupportSchema.nullable(),
  }),
  // Network Information.
  network: z.object({
    effectiveType: text.nullable(),
    downlinkMbps: measure.nullable(),
    rttMs: measure.nullable(),
    saveData: z.boolean().nullable(),
  }),
  // null: permission not granted (or not asked yet).
  displays: z.array(displaySchema).max(16).nullable(),
})
export type CollectedHardware = z.infer<typeof collectedHardwareSchema>

// What the web sends: the same, with deviceMemory rounded on the way in.
export const collectedHardwareInputSchema = collectedHardwareSchema.extend({
  deviceMemoryGb: deviceMemorySchema.nullable(),
})

export const CONNECTION_TYPES = ['wired', 'wifi', 'mobile', 'other'] as const

// What the browser can't see, filled in by the user and shown as "informed by
// the user". Every field is optional.
export const manualHardwareSchema = z.object({
  cpuModel: text.nullable(),
  ramGb: measure.nullable(),
  gpuModel: text.nullable(),
  vramGb: measure.nullable(),
  connectionType: z.enum(CONNECTION_TYPES).nullable(),
  internetDownloadMbps: measure.nullable(),
  internetUploadMbps: measure.nullable(),
})
export type ManualHardware = z.infer<typeof manualHardwareSchema>

export const reportDeviceRequestSchema = z.object({
  // Generated by the web and kept in the browser, one per device.
  deviceId: z.uuid(),
  collected: collectedHardwareInputSchema,
})
export type ReportDeviceRequest = z.input<typeof reportDeviceRequestSchema>

export const deviceReportSchema = z.object({
  id: z.string(),
  deviceId: z.string(),
  collected: collectedHardwareSchema,
  manual: manualHardwareSchema.nullable(),
  collectedAt: z.iso.datetime(),
})
export type DeviceReport = z.infer<typeof deviceReportSchema>

export const listDevicesResponseSchema = z.object({
  devices: z.array(deviceReportSchema),
})
export type ListDevicesResponse = z.infer<typeof listDevicesResponseSchema>
